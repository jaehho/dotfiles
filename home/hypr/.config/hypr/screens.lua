-- Screens: which workspaces each monitor holds.
--
-- Hyprland places monitors itself: the catch-all rule in hyprland.lua (each
-- monitor's own preferred mode, automatic position and scale) or the rules
-- nwg-displays saves to monitors.lua. This module only reads where they
-- ended up, and does what Hyprland will not: split workspaces 1-9 into one
-- block per monitor, and move them when a monitor comes or goes (issue
-- #9580 was closed as not planned). The closed set is 1-9, never 10.
-- Minting past 9 is a bug. Turning screens off and mirroring are
-- nwg-displays' (F1), saved with its other rules.
--
-- Blocks run left to right, the first monitors taking the remainder: one
-- monitor holds 1-9, two hold 1-5 and 6-9, three 1-3, 4-6 and 7-9.
-- Super+Ctrl+P (quick settings: Workspaces start here) gives the focused
-- monitor the first block in this setup, the others keeping left-to-right
-- order. The choice is saved per setup (the set of connected monitors) in
-- screens_primary.lua beside this file, generated and untracked. On the
-- leftmost monitor it clears the choice.

local LAPTOP_PATTERN = "eDP-"
local MAX_WORKSPACES = 9
local DEBOUNCE_MS    = 500

local function config_dir()
    local xdg = os.getenv("XDG_CONFIG_HOME")
    if xdg == nil or xdg == "" then
        xdg = os.getenv("HOME") .. "/.config"
    end
    return xdg .. "/hypr"
end
local PRIMARY_FILE = config_dir() .. "/screens_primary.lua"

local function is_laptop(m)
    return m.name:sub(1, #LAPTOP_PATTERN) == LAPTOP_PATTERN
end

-- Outputs showing their own picture, or with `all` every connected one
-- (turned off and mirroring too). With none left Hyprland invents one called
-- FALLBACK; that is not a screen, so it is left out.
local function monitors(all)
    local list = all and hl.get_monitors({ all = true }) or hl.get_monitors()
    local out = {}
    for _, m in ipairs(list or {}) do
        if m.name ~= "FALLBACK" then out[#out + 1] = m end
    end
    return out
end

-- A monitor mid-hotplug reports 0x0, and its position is not final either.
local function settled(live)
    if #live == 0 then return false end
    for _, m in ipairs(live) do
        if m.width == 0 or m.height == 0 then return false end
    end
    return true
end

-- Left to right as Hyprland placed them.
local function ordered(list)
    local out = { table.unpack(list) }
    table.sort(out, function(a, b)
        if a.x ~= b.x then return a.x < b.x end
        if a.y ~= b.y then return a.y < b.y end
        return a.name < b.name
    end)
    return out
end

-- The rule selector for an override. nwg-displays (use-desc) keys a
-- monitor's rule as "desc:<description>"; hl.monitor merges into a rule
-- with the same selector, so the override changes only the fields it sets
-- and lasts until the next config reload. A headless output (the tablet)
-- has no real description: its name.
local function selector(m)
    if m.backend == "drm" and (m.description or "") ~= "" then
        return "desc:" .. m.description
    end
    return m.name
end

local function override(m, fields)
    fields.output = selector(m)
    hl.monitor(fields)
end

-- A monitor as saved primaries name it: its description, so a setup is
-- recognised whichever port each monitor is plugged into. Not selector():
-- the monitor object has no backend field (0.57.2), so that one always
-- falls back to the port name.
local function identity(m)
    if (m.description or "") ~= "" then
        return "desc:" .. m.description
    end
    return m.name
end

-- A setup: the monitors showing a picture, by identity, sorted.
local function setup_key(live)
    local keys = {}
    for _, m in ipairs(live) do keys[#keys + 1] = identity(m) end
    table.sort(keys)
    return table.concat(keys, " + ")
end

-- Saved primaries: { [setup_key] = identity of the monitor holding 1 }.
-- Read on every use, so a hand edit counts at the next hotplug or
-- Super+Ctrl+R. A missing or broken file is no choice at all.
local function read_primaries()
    local chunk = loadfile(PRIMARY_FILE)
    if not chunk then return {} end
    local ok, saved = pcall(chunk)
    return (ok and type(saved) == "table") and saved or {}
end

local function write_primaries(saved)
    local keys = {}
    for k in pairs(saved) do keys[#keys + 1] = k end
    table.sort(keys)
    local lines = {
        "-- Generated by screens.lua (Super+Ctrl+P). The monitor holding",
        "-- workspace 1 in each setup; a setup not listed runs left to right.",
        "return {",
    }
    for _, k in ipairs(keys) do
        lines[#lines + 1] = string.format("    [%q] = %q,", k, saved[k])
    end
    lines[#lines + 1] = "}"
    local f, err = io.open(PRIMARY_FILE, "w")
    if not f then return false, err end
    f:write(table.concat(lines, "\n"), "\n")
    f:close()
    return true
end

-- The block layout for the live monitors: { [name] = {ids...} } and the
-- order the blocks went out in. Left to right, with this setup's saved
-- primary (when connected) moved to the front; the first 9 % n monitors
-- take one extra id. apply(), slots_by_monitor() and through it
-- workspace_pack.lua all read this.
local function plan(live)
    local order = ordered(live)
    local want = read_primaries()[setup_key(live)]
    if want then
        for i, m in ipairs(order) do
            if identity(m) == want then
                table.insert(order, 1, table.remove(order, i))
                break
            end
        end
    end

    local n = #order
    local base, extra = MAX_WORKSPACES // n, MAX_WORKSPACES % n
    local slots, ws = {}, 1
    for idx, m in ipairs(order) do
        local list = {}
        for _ = 1, base + (idx <= extra and 1 or 0) do
            list[#list + 1] = ws
            ws = ws + 1
        end
        slots[m.name] = list
    end
    return slots, order
end

-- Set below; apply() may need to retry after its oneshot is spent.
local schedule

-- Assign workspace blocks to the monitors as placed, and move any workspace
-- that sits on the wrong one.
local function apply()
    local live = monitors()
    if #live == 0 then
        -- Nothing visible: the laptop was turned off (in nwg-displays) and
        -- the last external just left. Turn the laptop (or any output) back
        -- on until the next reload.
        local all = monitors(true)
        local target
        for _, m in ipairs(all) do
            if is_laptop(m) then target = m end
        end
        target = target or all[1]
        if target then override(target, { disabled = false, mirror = "" }) end
        return
    end
    -- Mid-hotplug: wait it out. The oneshot that got here is spent, so arm
    -- another — nothing else will.
    if not settled(live) then
        schedule()
        return
    end

    local slots, order = plan(live)

    -- The first workspace of each block is its monitor's default, so a
    -- fresh workspace opens where you expect.
    local assigned = {}
    for _, m in ipairs(order) do
        for i, ws in ipairs(slots[m.name]) do
            assigned[ws] = m.name
            -- Not persistent: an empty workspace must die when you leave it
            -- so workspace.removed fires and workspace_pack.lua ripples the
            -- holes closed (tmux renumber-windows). Super+N creates id N if
            -- missing.
            hl.workspace_rule({ workspace = tostring(ws), monitor = m.name, default = i == 1 })
        end
    end

    -- Rules only bind workspaces at creation time, so existing ones have to be
    -- moved. Hyprland will not do this itself: issue #9580 was closed as not
    -- planned.
    for _, ws in ipairs(hl.get_workspaces() or {}) do
        local target = assigned[ws.id]
        if target then
            local mon = ws.monitor
            local current = type(mon) == "string" and mon or (mon and mon.name)
            if current ~= target then
                hl.dispatch(hl.dsp.workspace.move({ workspace = ws.id, monitor = target }))
            end
        end
    end

    -- Sweep monitors sitting on a workspace that is no longer theirs back to
    -- their default, then restore focus.
    local focused
    for _, m in ipairs(live) do
        if m.focused then focused = m.name end
    end

    local swept = false
    for _, m in ipairs(order) do
        local default = slots[m.name][1]
        local now = hl.get_monitor(m.name)
        local active = now and now.active_workspace
        -- active_workspace is a userdata (not a table) on 0.57, so read .id
        -- off anything that is not already a number.
        local id = active and (type(active) == "number" and active or active.id)
        if id and assigned[id] ~= m.name and default then
            -- set_workspace({ workspace = "N" }) does nothing when N exists
            -- already (0.57.1, checked live); the workspace object works. The
            -- table form is only good for creating it.
            local home = hl.get_workspace(tostring(default))
            if home then
                now:set_workspace(home)
            else
                now:set_workspace({ workspace = tostring(default) })
            end
            swept = true
        end
    end

    if swept and focused then
        hl.dispatch(hl.dsp.focus({ monitor = focused }))
    end

    -- Closed set 1-9: fold any stray (temp leak, Super+scroll mint, 9003) back
    -- into the slots so the bar and Super+N only ever see 1-9.
    local pack = package.loaded["workspace_pack"]
    if pack and pack.reclaim then
        pack.reclaim()
    end
end

-- Slot ids each output owns under the live layout (the same plan apply()
-- binds). workspace_pack.lua packs only into these so the id ↔ monitor map
-- holds. The scripts (hypr-tab-nonempty, hypr-move-project) read the same
-- map back from the workspace rules apply() sets.
local function slots_by_monitor()
    local live = monitors()
    if not settled(live) then return {} end
    return (plan(live))
end

-- Super+Ctrl+P: the focused monitor takes the first block in this setup,
-- saved for the next time the same monitors are connected. On the leftmost
-- monitor it clears the choice instead, back to left to right. Windows stay
-- where they are: workspace_pack.lua renumbers each monitor's workspaces
-- into its new block before apply() binds the ids, so nothing moves.
local function set_primary()
    local live = monitors()
    if not settled(live) then return end
    local focused
    for _, m in ipairs(live) do
        if m.focused then focused = m end
    end
    if not focused then return end

    local saved = read_primaries()
    local cleared = ordered(live)[1].name == focused.name
    saved[setup_key(live)] = (not cleared) and identity(focused) or nil
    local ok, err = write_primaries(saved)
    if not ok then
        hl.notification.create({ text = "screens.lua could not save: " .. tostring(err), timeout = 5000, icon = "error" })
        return
    end

    local pack = package.loaded["workspace_pack"]
    if pack and pack.adopt then pack.adopt() end
    apply()

    local mine = slots_by_monitor()[focused.name] or {}
    local text
    if #live == 1 then
        text = "One display: it holds workspaces 1–9"
    elseif cleared then
        text = string.format("Workspaces %d–%d here, left to right (no saved choice)", mine[1], mine[#mine])
    else
        text = string.format("Workspaces %d–%d here, saved for these displays", mine[1], mine[#mine])
    end
    hl.notification.create({ text = text, timeout = 2500, icon = "info" })
end

-- Trailing-edge debounce: hotplug fires several events in a burst.
-- opts.type is mandatory ("repeat" or "oneshot") and hl.timer returns nil
-- without it. Creating it armed also gives us the initial apply, since the
-- config is parsed before monitors can be queried; that covers startup and
-- every reload (no event fires on a reload).
local function new_timer()
    return hl.timer(function()
        apply()
    end, { timeout = DEBOUNCE_MS, type = "oneshot" })
end
local pending = new_timer()

-- While armed, set_enabled(true) restarts the countdown, which is the debounce.
-- A oneshot that has fired is spent (is_enabled() is nil and set_enabled
-- revives nothing), so that case needs a new timer.
schedule = function()
    if pending:is_enabled() then
        pending:set_enabled(true)
    else
        pending = new_timer()
    end
end

hl.on("monitor.added", schedule)
hl.on("monitor.removed", schedule)
-- Deliberately not monitor.layout_changed: moving workspaces changes the
-- layout, which would re-enter this.

-- An output arriving or leaving by a path that fires no event (the headless
-- tablet): clear a turned-off state its rule may still carry, so a new one
-- under the same name comes up on, and re-apply.
local function forget(name)
    hl.monitor({ output = name, disabled = false })
    schedule()
end

return {
    apply = apply,
    schedule = schedule,
    forget = forget,
    slots_by_monitor = slots_by_monitor,
    set_primary = set_primary,
}
